export function mockCustomerReply(customerId: string, messages: Message[]): string {
  const lastCounselor =
    [...messages].reverse().find((m) => m.role === "counselor")?.text ?? "";
  const turn = messages.filter((m) => m.role === "customer").length;

  for (const rule of RULES) {
    if (rule.match.test(lastCounselor)) {
      const pool = rule.replies[customerId] ?? rule.replies.jung;
      return pool[turn % pool.length];
    }
  }
  const pool = DEFAULTS[customerId] ?? DEFAULTS.jung;
  return pool[turn % pool.length];
}
